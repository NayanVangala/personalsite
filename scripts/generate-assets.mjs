// npm run assets. Generates every image the site needs from code, seeded and reproducible.
//   node scripts/generate-assets.mjs            everything
//   node scripts/generate-assets.mjs art        only the artworks (add --only=3,5 for specific ones)
//   groups: art, icons, og, textures
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import sharp from 'sharp';
import { makeRng } from './art/lib.mjs';
import { ARTWORKS } from './art/meta.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PUB = path.join(ROOT, 'public');
const args = process.argv.slice(2);
const only = (args.find((a) => a.startsWith('--only=')) ?? '').slice(7).split(',').filter(Boolean).map(Number);
const groups = args.filter((a) => !a.startsWith('--'));
const want = (g) => groups.length === 0 || groups.includes(g);

const summary = [];
const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
const out = async (rel, buf) => {
  const file = path.join(PUB, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, buf);
  summary.push([rel, buf.length]);
  return buf.length;
};

/* ------------------------------------------------------------------ art */

async function art() {
  const manifest = [];
  for (const m of ARTWORKS) {
    if (only.length && !only.includes(m.n)) continue;
    const t0 = Date.now();
    const rng = makeRng(m.seed);
    const mod = await import(pathToFileURL(path.join(ROOT, 'scripts/art', `${m.file}.mjs`)).href);
    const svg = await mod.default(rng, { w: m.w, h: m.h });
    if (m.vector) await out(`art/${m.id}.svg`, Buffer.from(svg));

    const png = await sharp(Buffer.from(svg), { limitInputPixels: false }).png().toBuffer();
    const full = await sharp(png).webp({ quality: 82, effort: 6, smartSubsample: true }).toBuffer();
    await out(`art/${m.id}.webp`, full);

    // small variant for tiles (srcset), long side 800
    const k = 800 / Math.max(m.w, m.h);
    const sw = Math.round(m.w * k), sh = Math.round(m.h * k);
    const sm = await sharp(png).resize(sw, sh, { kernel: 'lanczos3' }).webp({ quality: 80, effort: 6, smartSubsample: true }).toBuffer();
    await out(`art/${m.id}-sm.webp`, sm);

    // 24px blur-up placeholder, inlined into artworks.ts
    const lq = await sharp(png).resize(24, Math.round((24 * m.h) / m.w), { kernel: 'cubic' }).webp({ quality: 40 }).toBuffer();
    manifest.push({
      id: m.id,
      code: `NV-ID-I${String(m.n).padStart(2, '0')}`,
      src: `/art/${m.id}.webp`,
      srcSm: `/art/${m.id}-sm.webp`,
      svg: m.vector ? `/art/${m.id}.svg` : null,
      w: m.w, h: m.h, smW: sw, smH: sh,
      title: m.title, alt: m.alt, tone: m.tone, caption: m.caption,
      blur: `data:image/webp;base64,${lq.toString('base64')}`,
      bytes: full.length,
    });
    console.log(`  ${m.id} ${m.title.padEnd(16)} ${m.w}x${m.h}  ${kb(full.length)}  (${((Date.now() - t0) / 1000).toFixed(1)}s)`);
  }

  // only rewrite the manifest + ts when rendering the full set
  if (only.length === 0) writeManifest(manifest);
}

function writeManifest(manifest) {
  const slim = manifest.map(({ bytes, blur, ...rest }) => rest);
  fs.writeFileSync(path.join(ROOT, 'scripts/art/manifest.json'), JSON.stringify(slim, null, 2) + '\n');
  const ts = `// GENERATED by scripts/generate-assets.mjs from scripts/art/meta.mjs. Do not edit by hand, run \`npm run assets\`.
export type Artwork = {
  id: string;
  /** tile code shown in the HUD label */
  code: string;
  /** full size webp, long side 1600 */
  src: string;
  /** small webp for tiles, long side 800 */
  srcSm: string;
  /** vector source, when the piece is vector */
  svg: string | null;
  w: number;
  h: number;
  smW: number;
  smH: number;
  title: string;
  alt: string;
  /** CSS color for the blur-up backdrop, from the raw palette vars */
  tone: string;
  caption: string;
  /** tiny inlined webp, blurred up while the real image loads */
  blur: string;
};

export const ARTWORKS: Artwork[] = ${JSON.stringify(manifest.map(({ bytes, ...r }) => r), null, 2)};
`;
  fs.writeFileSync(path.join(ROOT, 'src/components/imagery/artworks.ts'), ts);
}

/* ------------------------------------------------------------------ main */

console.log('generating assets into public/');
const jobs = [['art', art]];
for (const [g, fn] of jobs) {
  if (!want(g)) continue;
  console.log(`[${g}]`);
  await fn();
}
console.log(`\n${summary.length} files written`);
for (const [f, n] of summary) console.log(`  ${f.padEnd(34)} ${kb(n)}`);
